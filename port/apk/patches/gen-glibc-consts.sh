#!/bin/bash
# Generates glibc_consts.h for the box64 glibc-on-bionic patch: tables mapping x86_64 glibc values of
# sysconf names, nl_langinfo items and glob flags to their bionic names.
# Usage: gen-glibc-consts.sh NDK_SYSROOT_INCLUDE OUT_HEADER
#   Needs adb (on PATH; ANDROID_SERIAL picks the device) and a rooted phone with a Debian chroot at
#   /data/local/dd/debian holding x86_64-linux-gnu-gcc and a glibc box64 (port/phone/). RX is a script
#   that runs its argument as root on the phone. The generated header is already part of
#   box64-glibc-on-bionic.patch: this is only needed to regenerate it.
set -e
W=$(mktemp -d -p "$(dirname "$2")") && trap 'rm -rf "$W"' EXIT
INC=$1 OUT=$2
RX=${RX:?set RX to the rx.sh that runs root commands on the phone}

names() { grep -hoE "^#define +$1[A-Z0-9_]* " "$2" | awk '{print $2}' | sort -u; }
{
  echo '#include <unistd.h>'
  echo '#include <langinfo.h>'
  echo '#include <glob.h>'
  echo '#include <stdio.h>'
  echo 'int main(void) {'
  for n in $(names _SC_ "$INC/bits/sysconf.h"); do
    echo "#ifdef $n"; echo "  printf(\"SC $n %d\\n\", (int)$n);"; echo "#endif"; done
  for n in $(grep -oE '^#define +[A-Z][A-Z0-9_]* +[0-9]+' "$INC/langinfo.h" | awk '{print $2}'); do
    echo "#ifdef $n"; echo "  printf(\"NL $n %d\\n\", (int)$n);"; echo "#endif"; done
  for n in GLOB_ERR GLOB_MARK GLOB_NOSORT GLOB_DOOFFS GLOB_NOCHECK GLOB_APPEND GLOB_NOESCAPE GLOB_NOSPACE GLOB_ABORTED GLOB_NOMATCH; do
    echo "  printf(\"GL $n %d\\n\", (int)$n);"; done
  echo '  return 0;'
  echo '}'
} > $W/glibc-consts.c

MSYS_NO_PATHCONV=1 adb push -q "$(cygpath -m $W/glibc-consts.c)" /data/local/tmp/glibc-consts.c
bash "$RX" 'R=/data/local/dd/debian; cp /data/local/tmp/glibc-consts.c $R/root/ &&
  chroot $R /usr/bin/env PATH=/usr/local/bin:/usr/bin:/bin sh -c "cd /root && x86_64-linux-gnu-gcc -o glibc-consts glibc-consts.c && box64 ./glibc-consts"' \
  | tr -d '\r' | grep -E '^(SC|NL|GL) ' > $W/glibc-consts.txt

{
  echo "// Generated by port/apk/patches/gen-glibc-consts.sh: x86_64 glibc value -> bionic constant."
  echo "// Guest code passes glibc numbers; bionic numbers these differently."
  for k in SC NL; do
    echo "static const int glibc_${k,,}_map[][2] = {"
    grep "^$k " $W/glibc-consts.txt | while read -r _ n v; do
      echo "#ifdef $n"; echo "    {$v, $n},"; echo "#endif"; done
    echo "};"
  done
  grep '^GL ' $W/glibc-consts.txt | while read -r _ n v; do echo "#define GLIBC_$n $v"; done
} > "$OUT"
echo "$(grep -c '^SC ' $W/glibc-consts.txt) sysconf, $(grep -c '^NL ' $W/glibc-consts.txt) langinfo, $(grep -c '^GL ' $W/glibc-consts.txt) glob constants -> $OUT"
